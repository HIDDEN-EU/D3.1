"""
DataLoader factory
------------------
Builds train / val / test DataLoaders from a manifest CSV.

Each dataset must have a manifest CSV generated by the corresponding prepare
script before this factory is called::

    python scripts/prepare_fer2013.py --root /path/to/fer2013
    python scripts/prepare_rafdb.py   --root /path/to/raf-db
    python scripts/prepare_kdef.py    --root /path/to/kdef-dataset

Split strategy is controlled by :class:`~emotion_recognition.config.SplitConfig`
in the experiment config.  See that class for full documentation.
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

import pandas as pd
import torch
from sklearn.model_selection import train_test_split
from torch.utils.data import DataLoader, WeightedRandomSampler

from torchvision import transforms as T

from emotion_recognition.config import AugmentationConfig, DatasetName, SplitConfig
from .base import ManifestDataset, compute_sample_weights
from .kdef import build_kdef_dataset
from .transforms import fer2013_transforms, ferplus_transforms, kdef_transforms, rafdb_transforms, affectnet_transforms


# ── Public API ────────────────────────────────────────────────────────────────


def build_loaders(
    dataset: DatasetName,
    root: str | Path,
    *,
    batch_size: int = 64,
    num_workers: int = 2,
    pin_memory: bool = True,
    use_weighted_sampler: bool = True,
    split_cfg: Optional[SplitConfig] = None,
    # KDEF metadata filters
    angles: Optional[list[str]] = None,
    genders: Optional[list[str]] = None,
    sessions: Optional[list[str]] = None,
    # Augmentation
    augmentation: Optional[AugmentationConfig] = None,
    # Optional transform overrides (used by SwinFace which needs 112×112 inputs)
    train_transform: Optional[T.Compose] = None,
    eval_transform: Optional[T.Compose] = None,
) -> dict[str, DataLoader]:
    """Build train / val / test DataLoaders from a manifest CSV.

    Parameters
    ----------
    dataset :
        Which dataset to load (``"fer2013"``, ``"kdef"``, ``"rafdb"``, ``"ferplus"``).
    root :
        Dataset root directory (must contain a ``{dataset}_manifest.csv``).
    batch_size :
        Batch size for all loaders.
    num_workers :
        Worker processes for data loading.
    pin_memory :
        Pin memory for faster GPU transfer.
    use_weighted_sampler :
        If ``True``, oversample minority classes in the training loader via
        :class:`~torch.utils.data.WeightedRandomSampler`.
    split_cfg :
        How to partition the manifest.  Defaults to ``SplitConfig()``
        (strategy ``"source"``, val_ratio 0.10).
    angles, genders, sessions :
        KDEF-specific subset filters (``None`` = keep all).
    augmentation :
        Augmentation parameters.  ``None`` uses per-dataset defaults.

    Returns
    -------
    dict with keys ``"train"``, ``"val"``, ``"test"``.

    Raises
    ------
    FileNotFoundError
        If the manifest CSV is missing — run the corresponding prepare script.
    """
    root = Path(root)
    split_cfg = split_cfg or SplitConfig()
    aug = augmentation or AugmentationConfig()

    if train_transform is not None and eval_transform is not None:
        train_tf, eval_tf = train_transform, eval_transform
    else:
        train_tf, eval_tf = _get_transforms(dataset, aug)

    df = _load_manifest(root, dataset)

    # Apply KDEF metadata filters before splitting
    if dataset == DatasetName.KDEF and any(f is not None for f in [angles, genders, sessions]):
        if angles is not None:
            df = df[df["angle"].isin(angles)]
        if genders is not None:
            df = df[df["gender"].isin(genders)]
        if sessions is not None:
            df = df[df["session"].isin(sessions)]
        df = df.reset_index(drop=True)

    train_df, val_df, test_df = _apply_split(df, split_cfg)

    if dataset == DatasetName.KDEF:
        train_ds = build_kdef_dataset(train_df, train_tf)
        val_ds   = build_kdef_dataset(val_df,   eval_tf)
        test_ds  = build_kdef_dataset(test_df,  eval_tf)
    else:
        train_ds = ManifestDataset(list(zip(train_df["path"], train_df["label"])), train_tf)
        val_ds   = ManifestDataset(list(zip(val_df["path"],   val_df["label"])),   eval_tf)
        test_ds  = ManifestDataset(list(zip(test_df["path"],  test_df["label"])),  eval_tf)

    return _make_loaders(
        train_ds, val_ds, test_ds,
        batch_size=batch_size,
        num_workers=num_workers,
        pin_memory=pin_memory,
        use_weighted_sampler=use_weighted_sampler,
    )


# ── Manifest loading ──────────────────────────────────────────────────────────


def _load_manifest(root: Path, dataset: str) -> pd.DataFrame:
    dataset_str = dataset.value if isinstance(dataset, DatasetName) else dataset
    path = root / f"{dataset_str}_manifest.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"Manifest not found: {path}\n"
            f"Run:  python scripts/prepare_{dataset_str}.py --root {root}"
        )
    return pd.read_csv(path)


# ── Split strategies ──────────────────────────────────────────────────────────


def _apply_split(
    df: pd.DataFrame, cfg: SplitConfig
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    if cfg.strategy == "source":
        return _source_split(df, cfg)
    return _ratio_split(df, cfg)


def _source_split(
    df: pd.DataFrame, cfg: SplitConfig
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Partition using the ``source_split`` column from the manifest."""
    test_df    = df[df["source_split"] == "test"].reset_index(drop=True)
    train_pool = df[df["source_split"] == "train"].reset_index(drop=True)

    if "val" in df["source_split"].values:
        # KDEF: official val split already present — use it, ignore val_ratio
        val_df = df[df["source_split"] == "val"].reset_index(drop=True)
    else:
        train_pool, val_df = _stratified_split(train_pool, cfg.val_ratio, cfg.seed, cfg.stratified)

    return train_pool, val_df, test_df


def _ratio_split(
    df: pd.DataFrame, cfg: SplitConfig
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Pool all rows and re-split from scratch by ratio."""
    df, test_df = _stratified_split(df, cfg.test_ratio, cfg.seed, cfg.stratified)
    # Recompute val_ratio relative to what remains after test is removed
    remaining_val_ratio = cfg.val_ratio / (1.0 - cfg.test_ratio) if cfg.test_ratio < 1 else 0.0
    df, val_df = _stratified_split(df, remaining_val_ratio, cfg.seed + 1, cfg.stratified)
    return df, val_df, test_df


def _stratified_split(
    df: pd.DataFrame, ratio: float, seed: int, stratified: bool
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Split df into (main, held_out); held_out is ``ratio`` fraction of df."""
    if ratio <= 0:
        return df.reset_index(drop=True), pd.DataFrame(columns=df.columns)
    stratify = df["label"] if stratified else None
    main, held_out = train_test_split(
        df, test_size=ratio, random_state=seed, stratify=stratify
    )
    return main.reset_index(drop=True), held_out.reset_index(drop=True)


# ── Transform dispatch ────────────────────────────────────────────────────────


def _get_transforms(dataset: str, aug: AugmentationConfig):
    if dataset == DatasetName.FER2013:
        return fer2013_transforms("train", aug), fer2013_transforms("test", aug)
    elif dataset == DatasetName.KDEF:
        return kdef_transforms("train", aug), kdef_transforms("val", aug)
    elif dataset == DatasetName.FERPLUS:
        return ferplus_transforms("train", aug), ferplus_transforms("test", aug)
    elif dataset == DatasetName.AFFECTNET:
        return affectnet_transforms("train", aug), affectnet_transforms("test", aug)
    else:  # DatasetName.RAFDB
        return rafdb_transforms("train", aug), rafdb_transforms("test", aug)


# ── DataLoader construction ───────────────────────────────────────────────────


def _make_loaders(
    train_ds: ManifestDataset,
    val_ds: ManifestDataset,
    test_ds: ManifestDataset,
    *,
    batch_size: int,
    num_workers: int,
    pin_memory: bool,
    use_weighted_sampler: bool,
) -> dict[str, DataLoader]:
    if use_weighted_sampler and len(train_ds) > 0:
        weights = compute_sample_weights(train_ds.targets)
        sampler = WeightedRandomSampler(
            weights=weights, num_samples=len(train_ds), replacement=True
        )
        train_loader = DataLoader(
            train_ds,
            batch_size=batch_size,
            sampler=sampler,
            num_workers=num_workers,
            pin_memory=pin_memory,
        )
    else:
        train_loader = DataLoader(
            train_ds,
            batch_size=batch_size,
            shuffle=True,
            num_workers=num_workers,
            pin_memory=pin_memory,
        )

    val_loader = DataLoader(
        val_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=pin_memory,
    )
    test_loader = DataLoader(
        test_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=pin_memory,
    )
    return {"train": train_loader, "val": val_loader, "test": test_loader}
